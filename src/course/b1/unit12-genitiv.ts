/** [id, sentence with ___, right, wrongA, wrongB, gender label] */
const GEN: [string, string, string, string, string, string][] = [
  ['m', 'Das ist das Fahrrad ___ Nachbarn.', 'des', 'der', 'dem', 'maskulin (der Nachbar → des Nachbarn, n-Deklination)'],
  ['f', 'Die Farbe ___ Jacke gefällt mir.', 'der', 'die', 'des', 'feminin → der'],
  ['n', 'Der Preis ___ Autos ist zu hoch.', 'des', 'das', 'dem', 'neutral → des (+ -s am Nomen)'],
  ['pl', 'Die Zimmer ___ Kinder sind im ersten Stock.', 'der', 'den', 'die', 'Plural → der'],
  ['wegen', 'Wegen ___ Staus kamen wir zu spät.', 'des', 'dem', 'den', 'wegen + Genitiv, der Stau → des Staus'],
  ['trotz', 'Trotz ___ Kälte gingen wir schwimmen.', 'der', 'die', 'den', 'trotz + Genitiv, die Kälte → der Kälte'],
  ['waehrend', 'Während ___ Unterrichts darf man nicht telefonieren.', 'des', 'dem', 'der', 'während + Genitiv, der Unterricht → des Unterrichts'],
]

function genDrills(): Exercise[] {
  return GEN.map(([id, sentence, right, wrongA, wrongB, why], i) => {
    const options = [right, wrongA, wrongB]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `gen-${id}`,
      type: 'multiple_choice' as const,
      topic: ['wegen', 'trotz', 'waehrend'].includes(id) ? 'gen-praep' : 'gen-artikel',
      concept: `gen-${id}`,
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(`Genitiv: ${why}.`, `Genitiv: ${why}.`, `Genitiv: ${why}.`),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

