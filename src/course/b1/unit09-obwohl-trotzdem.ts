const CONNECT: [string, string, 'obwohl' | 'weil' | 'trotzdem' | 'deshalb', string][] = [
  ['regen', 'Regen + spazieren gehen', 'obwohl', 'Ich gehe spazieren, ___ es regnet.'],
  ['muede', 'müde + früh ins Bett', 'weil', 'Ich gehe früh ins Bett, ___ ich müde bin.'],
  ['diaet', 'Diät + Kuchen essen', 'obwohl', '___ ich eine Diät mache, esse ich ein Stück Kuchen.'],
  ['krank', 'krank + zur Arbeit', 'trotzdem', 'Er ist krank. ___ geht er zur Arbeit.'],
  ['teuer', 'teuer + kaufen', 'trotzdem', 'Das Handy ist sehr teuer. ___ kaufe ich es.'],
  ['kalt', 'kalt + Jacke', 'deshalb', 'Es ist kalt. ___ nehme ich eine Jacke mit.'],
  ['gelernt', 'viel gelernt + Prüfung nicht bestanden', 'obwohl', 'Sie hat die Prüfung nicht bestanden, ___ sie viel gelernt hat.'],
]

function connectDrills(): Exercise[] {
  const all: Record<string, string[]> = {
    obwohl: ['obwohl', 'weil', 'damit'],
    weil: ['weil', 'obwohl', 'dass'],
    trotzdem: ['trotzdem', 'deshalb', 'obwohl'],
    deshalb: ['deshalb', 'trotzdem', 'weil'],
  }
  return CONNECT.map(([id, , right, sentence], i) => {
    const cap = sentence.startsWith('___')
    const c = (s: string) => (cap || /\. ___/.test(sentence) ? s[0].toUpperCase() + s.slice(1) : s)
    const options = all[right].map(c)
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    const why: Record<string, [string, string]> = {
      obwohl: ['Unexpected result in a subordinate clause → obwohl (verb at the end).', 'Yan cümlede beklenmedik sonuç → obwohl (fiil sonda).'],
      weil: ['Reason → weil.', 'Sebep → weil.'],
      trotzdem: ['Unexpected result, main clause → trotzdem + verb.', 'Beklenmedik sonuç, ana cümle → trotzdem + fiil.'],
      deshalb: ['Logical result → deshalb + verb.', 'Mantıklı sonuç → deshalb + fiil.'],
    }
    return {
      id: `konn-${id}`,
      type: 'multiple_choice' as const,
      topic: right === 'obwohl' ? 'obwohl' : right === 'trotzdem' ? 'trotzdem' : 'grund-folge',
      concept: `connector-${right}`,
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(c(right)),
      explanation: l(why[right][0], why[right][1], why[right][0]),
      examples: [sentence.replace('___', `**${c(right)}**`)],
    }
  })
}

