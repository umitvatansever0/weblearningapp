type Case = 'Nom' | 'Akk'
/** [id, sentence with ___, right pronoun, gender label, case] */
const REL_DRILLS: [string, string, string, string, Case][] = [
  ['nom-m', 'Der Kollege, ___ neben mir sitzt, kommt aus Italien.', 'der', 'maskulin', 'Nom'],
  ['nom-f', 'Die Bäckerei, ___ an der Ecke ist, hat sehr gutes Brot.', 'die', 'feminin', 'Nom'],
  ['nom-n', 'Das Restaurant, ___ neu eröffnet hat, ist teuer.', 'das', 'neutral', 'Nom'],
  ['nom-pl', 'Die Kinder, ___ im Park spielen, sind laut.', 'die', 'Plural', 'Nom'],
  ['akk-m', 'Der Film, ___ wir gestern gesehen haben, war spannend.', 'den', 'maskulin', 'Akk'],
  ['akk-f', 'Die Jacke, ___ du trägst, ist sehr schön.', 'die', 'feminin', 'Akk'],
  ['akk-n', 'Das Buch, ___ ich gerade lese, ist von Kafka.', 'das', 'neutral', 'Akk'],
  ['akk-pl', 'Die Freunde, ___ ich in Berlin besucht habe, wohnen jetzt in Köln.', 'die', 'Plural', 'Akk'],
]

function relDrills(): Exercise[] {
  return REL_DRILLS.map(([id, sentence, right, gender, kasus], i) => {
    const pool = ['der', 'den', 'die', 'das', 'dem'].filter((p) => p !== right)
    const preferred = kasus === 'Akk' && gender === 'maskulin' ? ['der', 'dem'] : kasus === 'Nom' && gender === 'maskulin' ? ['den', 'die'] : [pool[i % pool.length], pool[(i + 2) % pool.length]]
    const options = [right, ...preferred.filter((p) => p !== right)].slice(0, 3)
    while (options.length < 3) options.push(pool.find((p) => !options.includes(p)) as string)
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `rel-${id}`,
      type: 'multiple_choice' as const,
      topic: kasus === 'Nom' ? 'rel-nom' : 'rel-akk',
      concept: `rel-${id}`,
      skill: 'grammar' as const,
      difficulty: (kasus === 'Nom' ? 1 : 2) as 1 | 2,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: kasus === 'Nom'
        ? l(
            `The relative pronoun is the subject of the relative clause → Nominativ ${gender}: ${right}.`,
            `İlgi zamiri yan cümlenin öznesidir → Nominativ ${gender}: ${right}.`,
            `Subjekt im Relativsatz → ${right}.`
          )
        : l(
            `The relative pronoun is the object of the relative clause (the subject is ${sentence.includes('wir') ? 'wir' : sentence.includes('du') ? 'du' : 'ich'}) → Akkusativ ${gender}: ${right}.`,
            `İlgi zamiri yan cümlenin nesnesidir (özne ${sentence.includes('wir') ? 'wir' : sentence.includes('du') ? 'du' : 'ich'}) → Akkusativ ${gender}: ${right}.`,
            `Objekt im Relativsatz → ${right}.`
          ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

