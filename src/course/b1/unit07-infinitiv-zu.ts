/** [id, sentence with ___, right, wrong A, wrong B, note] */
const ZU_DRILLS: [string, string, string, string, string, string][] = [
  ['lust', 'Hast du Lust, heute Abend Pizza ___?', 'zu essen', 'essen', 'zu isst', 'Lust haben + zu + infinitive at the end'],
  ['wichtig', 'Es ist wichtig, jeden Tag Wasser ___.', 'zu trinken', 'trinken', 'zu getrunken', 'Es ist wichtig, … zu + infinitive'],
  ['vergessen', 'Ich habe vergessen, die Tür ___.', 'abzuschließen', 'zu abschließen', 'abschließen', 'separable verb: zu goes in the middle → abzuschließen'],
  ['versuchen', 'Ich versuche, mehr Deutsch ___.', 'zu sprechen', 'sprechen', 'zu spreche', 'versuchen + zu + infinitive'],
  ['anfangen', 'Es fängt an ___.', 'zu regnen', 'regnen', 'zu regnet', 'anfangen + zu + infinitive'],
  ['einkaufen', 'Ich habe keine Zeit, ___.', 'einzukaufen', 'zu einkaufen', 'einkaufen', 'separable verb: ein-zu-kaufen'],
  ['modal', 'Ich muss morgen früh ___.', 'aufstehen', 'aufzustehen', 'zu aufstehen', 'after modal verbs: NO zu'],
]

function zuDrills(): Exercise[] {
  return ZU_DRILLS.map(([id, sentence, right, wrongA, wrongB, note], i) => {
    const options = [right, wrongA, wrongB]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `zu-${id}`,
      type: 'multiple_choice' as const,
      topic: id === 'modal' ? 'ohne-zu' : id === 'vergessen' || id === 'einkaufen' ? 'trennbar-zu' : 'infinitiv-zu',
      concept: `zu-${id}`,
      skill: 'grammar' as const,
      difficulty: (id === 'vergessen' || id === 'einkaufen' || id === 'modal' ? 3 : 2) as 2 | 3,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(`${note}.`, `${note}.`, `${note}.`),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

