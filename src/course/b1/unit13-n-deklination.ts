/** [id, sentence with ___ for the noun, right, wrong] */
const N_DRILLS: [string, string, string, string][] = [
  ['kollege', 'Ich rufe morgen den neuen ___ an.', 'Kollegen', 'Kollege'],
  ['kunde', 'Die Verkäuferin hilft dem ___.', 'Kunden', 'Kunde'],
  ['herr', 'Ich habe einen Termin bei ___ Doktor Klein.', 'Herrn', 'Herr'],
  ['mensch', 'Er ist ein netter Mensch. Ich mag diesen ___.', 'Menschen', 'Mensch'],
  ['student', 'Die Professorin spricht mit dem ___.', 'Studenten', 'Student'],
  ['nachbar', 'Hast du den ___ schon kennengelernt?', 'Nachbarn', 'Nachbar'],
  ['junge', 'Wem gehört der Ball? – Dem ___ dort.', 'Jungen', 'Junge'],
]

function nDrills(): Exercise[] {
  return N_DRILLS.map(([id, sentence, right, wrong], i) => {
    const third = id === 'herr' ? 'Herren' : id === 'mensch' ? 'Menschs' : `${wrong}s`
    const options = [right, wrong, third]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `n-${id}`,
      type: 'multiple_choice' as const,
      topic: 'n-deklination',
      concept: `n-${id}`,
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        `${wrong} belongs to the n-declension: in Akkusativ, Dativ and Genitiv it gets -(e)n → ${right}.`,
        `${wrong} n-çekimine aittir: Akkusativ, Dativ ve Genitiv’de -(e)n alır → ${right}.`,
        `n-Deklination: ${right}.`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

