/** [id, sentence with ___ for lassen, person, right] */
const LASSEN: [string, string, string][] = [
  ['ich', 'Ich ___ mein Fahrrad reparieren.', 'lasse'],
  ['du', '___ du dir die Haare schneiden?', 'Lässt'],
  ['er', 'Er ___ seinen Anzug reinigen.', 'lässt'],
  ['wir', 'Wir ___ die Pizza liefern.', 'lassen'],
  ['ihr', '___ ihr die Wohnung renovieren?', 'Lasst'],
  ['perfekt', 'Ich habe meinen Schlüssel im Büro liegen ___.', 'lassen'],
]

const LASSEN_WRONG: Record<string, [string, string]> = {
  ich: ['lässt', 'lässe'],
  du: ['Lasst', 'Lasse'],
  er: ['lasst', 'lasse'],
  wir: ['lässt', 'lasst'],
  ihr: ['Lässt', 'Lassen'],
  perfekt: ['gelassen', 'lässt'],
}

function lassenDrills(): Exercise[] {
  return LASSEN.map(([id, sentence, right], i) => {
    const options = [right, ...LASSEN_WRONG[id]]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `lass-${id}`,
      type: 'multiple_choice' as const,
      topic: id === 'perfekt' ? 'lassen-perfekt' : 'lassen-formen',
      concept: `lassen-${id}`,
      skill: 'grammar' as const,
      difficulty: (id === 'perfekt' ? 3 : 1) as 1 | 3,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation:
        id === 'perfekt'
          ? l('Perfekt with another infinitive: habe … liegen lassen (not gelassen).', 'Başka bir mastarla Perfekt: habe … liegen lassen (gelassen değil).', 'liegen lassen.')
          : l(`lassen: ich lasse, du lässt, er lässt, wir lassen, ihr lasst, sie lassen → ${right}.`, `lassen: ich lasse, du lässt, er lässt, wir lassen, ihr lasst, sie lassen → ${right}.`, `${right}.`),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

