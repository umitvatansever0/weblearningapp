/** [id, sentence with ___ for the verb, right verb, two wrong] */
const NVV: [string, string, string, [string, string]][] = [
  ['entscheidung', 'Wir müssen heute eine Entscheidung ___.', 'treffen', ['machen', 'geben']],
  ['frage', 'Darf ich Ihnen eine Frage ___?', 'stellen', ['machen', 'fragen']],
  ['erfahrung', 'Im Ausland habe ich viele Erfahrungen ___.', 'gesammelt', ['gemacht', 'genommen']],
  ['verantwortung', 'In meinem Job ___ ich viel Verantwortung.', 'übernehme', ['nehme', 'mache']],
  ['vorschlag', 'Ich möchte einen Vorschlag ___.', 'machen', ['stellen', 'treffen']],
  ['kontakt', 'Bitte nehmen Sie bis Montag Kontakt mit uns ___.', 'auf', ['an', 'ein']],
  ['frage-kommen', 'Ein Umzug nach Berlin kommt für mich nicht in Frage. → Das ist für mich keine ___.', 'Option', ['Frage', 'Antwort']],
]

function nvvDrills(): Exercise[] {
  return NVV.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `nvv-${id}`,
      type: 'multiple_choice' as const,
      topic: 'nomen-verb',
      concept: `nvv-${id}`,
      skill: 'vocabulary' as const,
      difficulty: 2 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Noun–verb combinations are fixed – learn them as one unit.',
        'İsim–fiil birleşimleri sabittir – onları bir bütün olarak öğren.',
        'Feste Verbindung – als Einheit lernen.'
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

