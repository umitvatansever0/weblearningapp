/** [id, active sentence, passive subject, werden-form, rest, participle] */
const PASSIVE: [string, string, string, 'wird' | 'werden', string, string][] = [
  ['brot', 'Der Bäcker backt das Brot.', 'Das Brot', 'wird', 'vom Bäcker', 'gebacken'],
  ['autos', 'Die Firma produziert Autos.', 'Autos', 'werden', 'von der Firma', 'produziert'],
  ['briefe', 'Die Post liefert die Briefe.', 'Die Briefe', 'werden', 'von der Post', 'geliefert'],
  ['muell', 'Die Stadt sammelt den Müll.', 'Der Müll', 'wird', 'von der Stadt', 'gesammelt'],
  ['tuer', 'Der Hausmeister öffnet die Tür.', 'Die Tür', 'wird', 'vom Hausmeister', 'geöffnet'],
  ['essen', 'Der Koch bereitet das Essen zu.', 'Das Essen', 'wird', 'vom Koch', 'zubereitet'],
]

function passiveDrills(): Exercise[] {
  return PASSIVE.map(([id, active, subject, aux, agent, part], i) => {
    const right = `${subject} ${aux} ${agent} ${part}.`
    const wrongAux = aux === 'wird' ? 'werden' : 'wird'
    const wrongA = `${subject} ${wrongAux} ${agent} ${part}.`
    const wrongB = `${subject} ${aux} ${part} ${agent}.`
    const options = [right, wrongA, wrongB]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `pass-${id}`,
      type: 'multiple_choice' as const,
      topic: 'passiv-bildung',
      concept: aux === 'wird' ? 'passiv-wird' : 'passiv-werden',
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: active,
      promptL10n: l('Which is the correct passive sentence?', 'Hangisi doğru edilgen cümle?', 'Welcher Passivsatz ist richtig?'),
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        `The object becomes the subject (${subject}) → werden agrees with it (${aux}); participle at the end; agent with von.`,
        `Nesne özne olur (${subject}) → werden ona uyar (${aux}); ortaç sonda; yapan von ile.`,
        `${subject} ${aux} … ${part}.`
      ),
      examples: [`${subject} **${aux}** ${agent} **${part}**.`],
    }
  })
}

