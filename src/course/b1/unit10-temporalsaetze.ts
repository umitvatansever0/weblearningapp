function tempDrills(): Exercise[] {
  const meaning: Record<string, [string, string]> = {
    während: ['two things at the same time', 'iki şey aynı anda'],
    bevor: ['the other action happens first', 'diğer eylem önce olur'],
    seitdem: ['started in the past, still true', 'geçmişte başladı, hâlâ geçerli'],
    bis: ['up to the moment when …', '… olduğu ana kadar'],
    als: ['one time / period in the past', 'geçmişte bir kez / bir dönem'],
    wenn: ['every time (repeated)', 'her seferinde (tekrarlanan)'],
    sobald: ['immediately after', 'hemen ardından'],
  }
  return TEMP.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    const key = right.toLowerCase()
    return {
      id: `temp-${id}`,
      type: 'multiple_choice' as const,
      topic: key === 'als' || key === 'wenn' ? 'als-wenn' : 'temporal',
      concept: `temp-${key}`,
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(`${right}: ${meaning[key][0]}.`, `${right}: ${meaning[key][1]}.`, `${right}.`),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

