const PERSONS = ['ich', 'du', 'er', 'wir', 'ihr', 'sie'] as const
const ENDING: Record<(typeof PERSONS)[number], string> = { ich: 'e', du: 'st', er: 't', wir: 'en', ihr: 't', sie: 'en' }

/** Present tense of a regular verb; stems in -t/-d insert -e- (du arbeitest). */
export function conjugate(infinitive: string, person: (typeof PERSONS)[number]): string {
  const stem = infinitive.replace(/en$|n$/, '')
  const ending = ENDING[person]
  const needsE = /[td]$/.test(stem) && (ending === 'st' || ending === 't')
  return `${stem}${needsE ? 'e' : ''}${ending}`
}

const DRILL_VERBS = ['lernen', 'kochen', 'spielen', 'arbeiten', 'kaufen', 'trinken']

/** "wir ___ (lernen)" drills with the three most confusable forms. */
function conjugationDrills(): Exercise[] {
  return DRILL_VERBS.flatMap((verb, v) =>
    PERSONS.filter((_, p) => (p + v) % 2 === 0).map((person, i) => {
      const right = conjugate(verb, person)
      const forms = [...new Set(['ich', 'du', 'er', 'wir'].map((p) => conjugate(verb, p as (typeof PERSONS)[number])))].filter((f) => f !== right)
      const options = [right, forms[i % forms.length], forms[(i + 1) % forms.length]]
      const rotation = (v + i) % 3
      const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
      return {
        id: `v-${verb}-${person}`,
        type: 'multiple_choice' as const,
        topic: 'endings',
        concept: `ending-${person}`,
        skill: 'grammar' as const,
        difficulty: 1 as const,
        prompt: `${person} ___ (${verb})`,
        options: ordered,
        answer: ordered.indexOf(right),
        explanation: l(
          `${person} → -${ENDING[person]}: ${person} ${right}.`,
          `${person} → -${ENDING[person]}: ${person} ${right}.`,
          `${person} → -${ENDING[person]}: ${person} ${right}.`
        ),
      }
    })
  )
}

