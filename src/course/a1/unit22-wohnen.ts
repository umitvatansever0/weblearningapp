const AKK: Record<Gender, string> = { m: 'einen', f: 'eine', n: 'ein' }
const DRILL_NOUNS = ['Tisch', 'Stuhl', 'Schrank', 'Balkon', 'Lampe', 'Waschmaschine', 'Bett', 'Sofa', 'Regal', 'Garten']
const ALL = [...VOCAB, ...MORE_VOCAB]

function esGibtDrills(): Exercise[] {
  return DRILL_NOUNS.map((word, i) => {
    const v = ALL.find((x) => x.word === word)!
    const g = v.gender as Gender
    const options = i % 2 === 0 ? ['einen', 'eine', 'ein'] : ['ein', 'einen', 'eine']
    return {
      id: `gibt-${word.toLowerCase()}`,
      type: 'multiple_choice' as const,
      topic: 'es-gibt',
      concept: `es-gibt-${g}`,
      skill: 'grammar' as const,
      difficulty: 1 as const,
      prompt: `${v.emoji ? `${v.emoji} ` : ''}In der Wohnung gibt es ___ ${word}.`,
      options,
      answer: options.indexOf(AKK[g]),
      explanation: l(
        `es gibt + Akkusativ: ${g === 'm' ? 'der' : g === 'f' ? 'die' : 'das'} ${word} → ${AKK[g]} ${word}.`,
        `es gibt + Akkusativ: ${g === 'm' ? 'der' : g === 'f' ? 'die' : 'das'} ${word} → ${AKK[g]} ${word}.`,
        `es gibt + Akkusativ: ${AKK[g]} ${word}.`
      ),
      examples: [`Es gibt {${g}:${AKK[g]} ${word}}.`],
    }
  })
}

