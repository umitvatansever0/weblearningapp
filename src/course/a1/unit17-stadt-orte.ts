const IN_FORM: Record<Gender, string> = { m: 'im', f: 'in der', n: 'im' }
const DRILL_PLACES = ['Kino', 'Park', 'Restaurant', 'Hotel', 'Supermarkt', 'Museum', 'Schule', 'Apotheke', 'Bank', 'Bäckerei', 'Krankenhaus']

/** Wo bist du? – im Kino / in der Schule (in + Dativ as fixed phrases). */
function whereDrills(): Exercise[] {
  const all = [...VOCAB, ...MORE_VOCAB]
  return DRILL_PLACES.map((word, i) => {
    const v = all.find((x) => x.word === word)!
    const gender = v.gender as Gender
    const right = IN_FORM[gender]
    const options = ['im', 'in der', 'in den']
    return {
      id: `wo-${word.toLowerCase()}`,
      type: 'multiple_choice' as const,
      topic: 'wo-im',
      concept: `wo-in-${gender}`,
      skill: 'grammar' as const,
      difficulty: 1 as const,
      prompt: `${v.emoji ? `${v.emoji} ` : ''}Ich bin ___ ${word}.`,
      options: i % 2 === 0 ? options : [...options].reverse(),
      answer: (i % 2 === 0 ? options : [...options].reverse()).indexOf(right),
      explanation: l(
        `${gender === 'f' ? 'die' : gender === 'm' ? 'der' : 'das'} ${word} → Wo? ${right} ${word}. (der/das → im, die → in der)`,
        `${gender === 'f' ? 'die' : gender === 'm' ? 'der' : 'das'} ${word} → Wo? ${right} ${word}. (der/das → im, die → in der)`,
        `${gender === 'f' ? 'die' : gender === 'm' ? 'der' : 'das'} ${word} → Wo? ${right} ${word}.`
      ),
      examples: [`Ich bin **${right} ${word}**.`],
    }
  })
}

