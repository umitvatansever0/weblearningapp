const ART_NOM: Record<Gender, string> = { m: 'der', f: 'die', n: 'das' }
const INDEF_AKK: Record<Gender, string> = { m: 'einen', f: 'eine', n: 'ein' }
const DRILL_VERBS = ['habe', 'kaufe', 'brauche', 'suche']

/** "Ich kaufe ___ Apfel." – ein, eine or einen? */
function akkusativDrills(): Exercise[] {
  return [...VOCAB, ...MORE_VOCAB]
    .filter((v): v is VocabItem & { gender: Gender } => Boolean(v.gender) && v.word !== 'Zeit')
    .map((v, i) => {
      const verb = DRILL_VERBS[i % DRILL_VERBS.length]
      const options = ['ein', 'eine', 'einen']
      const right = INDEF_AKK[v.gender]
      const why =
        v.gender === 'm'
          ? {
              en: `${v.word} is masculine (der ${v.word}). After „${verb}“ the object is Akkusativ: ein → einen.`,
              tr: `${v.word} eril bir isim (der ${v.word}). „${verb}“ fiilinden sonra nesne Akkusativ olur: ein → einen.`,
              de: `${v.word} ist maskulin (der ${v.word}). Nach „${verb}“ steht das Objekt im Akkusativ: ein → einen.`,
            }
          : {
              en: `${ART_NOM[v.gender]} ${v.word} is ${v.gender === 'f' ? 'feminine' : 'neuter'} – it does not change in the Akkusativ: ${right} ${v.word}.`,
              tr: `${ART_NOM[v.gender]} ${v.word} ${v.gender === 'f' ? 'dişil' : 'nötr'} – Akkusativ’de değişmez: ${right} ${v.word}.`,
              de: `${ART_NOM[v.gender]} ${v.word} ist ${v.gender === 'f' ? 'feminin' : 'neutral'} – im Akkusativ ändert sich nichts: ${right} ${v.word}.`,
            }
      return {
        id: `akk-${v.word.toLowerCase()}`,
        type: 'multiple_choice' as const,
        topic: 'akk-forms',
        concept: `akk-indef-${v.gender}`,
        skill: 'grammar' as const,
        difficulty: 1 as const,
        prompt: `${v.emoji ? `${v.emoji} ` : ''}Ich ${verb} ___ ${v.word}.`,
        options,
        answer: options.indexOf(right),
        explanation: why,
        examples: [`Ich ${verb} {${v.gender}:${right} ${v.word}}.`],
      }
    })
}

