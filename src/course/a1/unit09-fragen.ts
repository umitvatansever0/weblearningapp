/** "___ wohnst du? – In Hamburg." drills with confusable question words. */
function questionWordDrills(): Exercise[] {
  return QA.map(([word, rest, reply, wrong], i) => {
    const options = [word, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `qw-${i + 1}`,
      type: 'multiple_choice' as const,
      topic: 'w-words',
      concept: ['Wo', 'Woher', 'Wohin'].includes(word) ? 'wo-woher-wohin' : 'w-word',
      skill: 'grammar' as const,
      difficulty: 1 as const,
      prompt: `___ ${rest}? – ${reply}`,
      options: ordered,
      answer: ordered.indexOf(word),
      explanation: l(
        `The answer „${reply}“ tells you the question word: ${word}?`,
        `„${reply}“ cevabı soru kelimesini gösterir: ${word}?`,
        `Die Antwort „${reply}“ zeigt das Fragewort: ${word}?`
      ),
      examples: [`**${word}** ${rest}? – ${reply}`],
    }
  })
}

