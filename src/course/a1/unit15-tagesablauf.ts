/** [subject, conjugated verb, prefix, middle] – the prefix goes to the end. */
const SEPARABLE: [string, string, string, string][] = [
  ['Ich', 'stehe', 'auf', 'um sieben Uhr'],
  ['Er', 'kauft', 'ein', 'im Supermarkt'],
  ['Wir', 'sehen', 'fern', 'am Abend'],
  ['Du', 'rufst', 'an', 'deine Mutter'],
  ['Sie', 'räumt', 'auf', 'ihr Zimmer'],
  ['Der Kurs', 'fängt', 'an', 'um neun Uhr'],
  ['Ich', 'kaufe', 'ein', 'am Samstag'],
  ['Ihr', 'steht', 'auf', 'sehr früh'],
]

function separableDrills(): Exercise[] {
  return SEPARABLE.map(([subject, verb, prefix, middle], i) => {
    const right = `${subject} ${verb} ${middle} ${prefix}.`
    const glued = `${subject} ${prefix}${verb} ${middle}.`
    const early = `${subject} ${verb} ${prefix} ${middle}.`
    const options = [right, glued, early]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `sep-${i + 1}`,
      type: 'multiple_choice' as const,
      topic: 'separable',
      concept: 'separable',
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: `${subject} … ${prefix}?`,
      promptL10n: l('Which sentence is correct?', 'Hangi cümle doğru?', 'Welcher Satz ist richtig?'),
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        `Separable verb: „${verb}“ in position 2, the prefix „${prefix}“ at the very end.`,
        `Ayrılabilen fiil: „${verb}“ 2. sırada, ön ek „${prefix}“ en sonda.`,
        `Trennbares Verb: „${verb}“ auf Position 2, „${prefix}“ am Ende.`
      ),
      examples: [`${subject} **${verb}** ${middle} **${prefix}**.`],
    }
  })
}

