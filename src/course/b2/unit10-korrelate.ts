function daDrills(): Exercise[] {
  return DA.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `da-${id}`,
      type: 'multiple_choice' as const,
      topic: 'da-woerter',
      concept: 'choose-correlate',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'The da-word comes from the verb’s preposition: freuen auf → darauf, denken an → daran, kümmern um → darum, Angst vor → davor, ärgern über → darüber.',
        'da-kelimesi fiilin edatından gelir: freuen auf → darauf, denken an → daran, kümmern um → darum, Angst vor → davor, ärgern über → darüber.',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

