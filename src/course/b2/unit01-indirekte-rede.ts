/** [id, indicative, Konjunktiv I, wrong forms] */
const FORMS: [string, string, string, [string, string]][] = [
  ['sein', 'er ist', 'er sei', ['er seie', 'er sein']],
  ['haben', 'sie hat', 'sie habe', ['sie hatte', 'sie habt']],
  ['kommen', 'er kommt', 'er komme', ['er käme', 'er kommte']],
  ['koennen', 'sie kann', 'sie könne', ['sie kanne', 'sie konnte']],
  ['wissen', 'er weiß', 'er wisse', ['er weisse', 'er wusste']],
  ['werden', 'es wird', 'es werde', ['es wirde', 'es wurde']],
]

function formDrills(): Exercise[] {
  return FORMS.map(([id, indicative, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `konj1-${id}`,
      type: 'multiple_choice' as const,
      topic: 'konjunktiv-i',
      concept: 'k1-forms',
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: `„${indicative}“ – Wie heißt der Konjunktiv I?`,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        `Konjunktiv I: infinitive stem + -e (er komme, sie habe). Only „sein“ is irregular: er sei. → ${right}`,
        `Konjunktiv I: mastar kökü + -e (er komme, sie habe). Tek düzensiz fiil „sein“dir: er sei. → ${right}`,
        `Konjunktiv I: Stamm + -e (er komme), aber sein → er sei. → ${right}`
      ),
    }
  })
}

