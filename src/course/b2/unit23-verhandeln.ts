const VER: [string, string, 0 | 1 | 2][] = [
  ['vorschlagen', 'Ich schlage vor, dass wir …', 0],
  ['frage', 'Das kommt für mich nicht in Frage.', 1],
  ['mitte', 'Wie wäre es, wenn wir uns in der Mitte treffen?', 2],
  ['halten', 'Was halten Sie davon, wenn …?', 0],
  ['entgegen', 'Da kann ich Ihnen leider nicht entgegenkommen.', 1],
  ['beide', 'Dann geben wir beide ein bisschen nach.', 2],
]

function verDrills(): Exercise[] {
  return VER.map(([id, phrase, right], i) => {
    const options = [...FUNCS]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `ver-${id}`,
      type: 'multiple_choice' as const,
      topic: 'redemittel',
      concept: 'functions',
      skill: 'speaking' as const,
      difficulty: 2 as const,
      prompt: `„${phrase}“ – Was ist das?`,
      options: ordered,
      answer: ordered.indexOf(FUNCS[right]),
      explanation: l(`→ ${FUNCS[right]}`, `→ ${FUNCS[right]}`, `→ ${FUNCS[right]}`),
    }
  })
}

