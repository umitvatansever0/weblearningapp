const SUF: [string, string, string, [string, string]][] = [
  ['frei', 'frei', 'die Freiheit', ['die Freikeit', 'die Freiung']],
  ['moeglich', 'möglich', 'die Möglichkeit', ['die Möglichheit', 'die Möglichung']],
  ['entscheiden', 'entscheiden', 'die Entscheidung', ['die Entscheidheit', 'die Entscheidkeit']],
  ['freund', 'der Freund', 'die Freundschaft', ['die Freundung', 'die Freundkeit']],
  ['gesund', 'gesund', 'die Gesundheit', ['die Gesundkeit', 'die Gesundschaft']],
  ['sauber', 'sauber', 'die Sauberkeit', ['die Sauberheit', 'die Sauberschaft']],
]

function sufDrills(): Exercise[] {
  return SUF.map(([id, base, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `suf-${id}`,
      type: 'multiple_choice' as const,
      topic: 'suffixe',
      concept: 'noun-suffix',
      skill: 'vocabulary' as const,
      difficulty: 2 as const,
      prompt: `„${base}“ → Nomen?`,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Rule of thumb: -keit after -ig, -lich, -bar, -sam and many adjectives in -el/-er; otherwise -heit. Verbs → -ung. Groups/relations → -schaft. All are feminine (die).',
        'Pratik kural: -ig, -lich, -bar, -sam ve -el/-er ile biten birçok sıfattan sonra -keit; diğerlerinde -heit. Fiiller → -ung. Gruplar/ilişkiler → -schaft. Hepsi dişil (die).',
        `→ ${right}`
      ),
    }
  })
}

