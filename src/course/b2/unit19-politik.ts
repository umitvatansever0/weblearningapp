function polDrills(): Exercise[] {
  return POL.map(([id, definition, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `pol-${id}`,
      type: 'multiple_choice' as const,
      topic: 'system',
      concept: 'definitions',
      skill: 'vocabulary' as const,
      difficulty: 2 as const,
      prompt: `„${definition}“`,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(`→ ${right}`, `→ ${right}`, `→ ${right}`),
    }
  })
}

