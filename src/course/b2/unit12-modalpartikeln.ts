/** [id, situation, right sentence, wrong] */
const PART: [string, string, string, [string, string]][] = [
  ['mal', 'Eine freundliche Bitte', 'Kannst du mal das Fenster aufmachen?', ['Kannst du ja das Fenster aufmachen?', 'Kannst du halt das Fenster aufmachen?']],
  ['ja', 'Überraschung: Dein Freund kommt im Regen herein.', 'Du bist ja ganz nass!', ['Du bist mal ganz nass!', 'Du bist denn ganz nass!']],
  ['denn', 'Interessierte Frage an eine neue Kollegin', 'Wo wohnst du denn?', ['Wo wohnst du mal?', 'Wo wohnst du halt?']],
  ['doch', 'Du möchtest, dass ein Freund mitkommt.', 'Komm doch einfach mit!', ['Komm denn einfach mit!', 'Komm eigentlich einfach mit!']],
  ['halt', 'Man kann nichts ändern.', 'Das ist halt so.', ['Das ist denn so.', 'Das ist bitte so.']],
  ['eigentlich', 'Du wechselst das Thema.', 'Wie spät ist es eigentlich?', ['Wie spät ist es halt?', 'Wie spät ist es mal?']],
]

function partDrills(): Exercise[] {
  return PART.map(([id, situation, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `part-${id}`,
      type: 'multiple_choice' as const,
      topic: 'funktion',
      concept: 'choose-particle',
      skill: 'speaking' as const,
      difficulty: 2 as const,
      prompt: `${situation} – Was sagst du?`,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'mal = soft request, ja = surprise, denn = interested question, doch = friendly push, halt = resignation, eigentlich = topic change.',
        'mal = yumuşak rica, ja = şaşkınlık, denn = ilgili soru, doch = dostça teşvik, halt = kabullenme, eigentlich = konu değişimi.',
        `→ ${right}`
      ),
    }
  })
}

