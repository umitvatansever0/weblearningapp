/** [id, sentence with gap, right, wrong] */
const ZAHL: [string, string, string, [string, string]][] = [
  ['von', 'Die Inflation stieg ___ 2 Prozent auf 5 Prozent.', 'von', ['um', 'bei']],
  ['auf', 'Die Arbeitslosigkeit sank von 6 ___ 5 Prozent.', 'auf', ['um', 'mit']],
  ['um', 'Der Umsatz ist im letzten Jahr ___ 10 Prozent gestiegen.', 'um', ['mit', 'an']],
  ['bei', 'Die Inflation liegt derzeit ___ 2,5 Prozent.', 'bei', ['an', 'zu']],
  ['werbung', 'Viele kaufen Dinge, die sie nicht brauchen – oft wegen der ___.', 'Werbung', ['Inflation', 'Lieferkette']],
  ['nachhaltig', 'Kleidung aus zweiter Hand zu kaufen, ist ___.', 'nachhaltig', ['verschwendet', 'geworben']],
]

function zahlDrills(): Exercise[] {
  return ZAHL.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `wirt-${id}`,
      type: 'multiple_choice' as const,
      topic: 'zahlen',
      concept: 'trends',
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'steigen/sinken von X auf Y (from/to), um Z (by), liegen bei (stand at).',
        'steigen/sinken von X auf Y (… -den … -e), um Z (… kadar), liegen bei (… seviyesinde).',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

