/** [id, sentence with gap, right, wrong] */
const KON: [string, string, string, [string, string]][] = [
  ['zumal', 'Ich nehme das Angebot nicht an, ___ das Gehalt auch zu niedrig ist.', 'zumal', ['wohingegen', 'geschweige denn']],
  ['wohingegen', 'In Berlin sind die Mieten gestiegen, ___ sie in Leipzig fast gleich geblieben sind.', 'wohingegen', ['zumal', 'sofern']],
  ['geschweige', 'Er spricht kaum Englisch, ___ Chinesisch.', 'geschweige denn', ['zumal', 'demnach']],
  ['ohnehin', 'Mach dir keine Sorgen, ich muss ___ in die Stadt.', 'ohnehin', ['geschweige', 'wohingegen']],
  ['nichtsdestotrotz', 'Die Bedingungen waren schwierig. ___ haben wir das Ziel erreicht.', 'Nichtsdestotrotz', ['Zumal', 'Sofern']],
  ['kaum', '___ dass der Film begonnen hatte, schlief er ein.', 'Kaum', ['Zumal', 'Wohingegen']],
]

function konDrills(): Exercise[] {
  return KON.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `kon-${id}`,
      type: 'multiple_choice' as const,
      topic: 'bedeutung',
      concept: 'choose-connector',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'zumal = additional reason, wohingegen = contrast, geschweige denn = let alone (after a negative), ohnehin = anyway, nichtsdestotrotz = nevertheless, kaum dass = no sooner than.',
        'zumal = ek sebep, wohingegen = karşıtlık, geschweige denn = … şöyle dursun (olumsuzdan sonra), ohnehin = zaten, nichtsdestotrotz = buna rağmen, kaum dass = … -er … -mez.',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

