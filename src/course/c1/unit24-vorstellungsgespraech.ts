const VG: [string, string, string, [string, string]][] = [
  ['zeichne', 'Ich ___ mich vor allem durch meine strukturierte Arbeitsweise aus.', 'zeichne', ['zeige', 'mache']],
  ['uebernommen', 'In meiner letzten Position habe ich Verantwortung für ein Team von zehn Personen ___.', 'übernommen', ['genommen', 'übergenommen']],
  ['lege', 'Ich ___ großen Wert auf eine offene Feedbackkultur.', 'lege', ['setze', 'stelle']],
  ['liegt', 'Meine Gehaltsvorstellung ___ bei 72.000 Euro brutto im Jahr.', 'liegt', ['steht', 'ist bei']],
  ['waere', 'Ein Einstieg zum ersten April ___ für mich durchaus denkbar.', 'wäre', ['war', 'würde']],
  ['betraegt', 'Meine Kündigungsfrist ___ drei Monate zum Quartalsende.', 'beträgt', ['trägt', 'bezahlt']],
]

function vgDrills(): Exercise[] {
  return VG.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `vg-${id}`,
      type: 'multiple_choice' as const,
      topic: 'staerken',
      concept: 'interview-phrases',
      skill: 'speaking' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Interview phrases: sich durch … auszeichnen (separable: ich zeichne mich … aus), Verantwortung übernehmen (übernommen), Wert legen auf, die Gehaltsvorstellung liegt bei …, wäre denkbar (Konjunktiv II = polite), die Frist beträgt …',
        'Mülakat kalıpları: sich durch … auszeichnen (ayrılabilir: ich zeichne mich … aus), Verantwortung übernehmen (übernommen), Wert legen auf, die Gehaltsvorstellung liegt bei …, wäre denkbar (Konjunktiv II = kibar), die Frist beträgt …',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

