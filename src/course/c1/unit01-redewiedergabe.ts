/** [id, sentence with gap, right, wrong] */
const RW: [string, string, string, [string, string]][] = [
  ['zufolge', 'Dem Bericht ___ sind die Mieten stark gestiegen.', 'zufolge', ['zuliebe', 'gegenüber']],
  ['laut', '___ Polizei gab es bei dem Unfall keine Verletzten.', 'Laut', ['Zufolge', 'Trotz']],
  ['wie', '___ der Minister betonte, bleibt die Steuer unverändert.', 'Wie', ['Was', 'Womit']],
  ['angeblich', 'Er hat ___ im Lotto gewonnen – aber niemand glaubt ihm.', 'angeblich', ['nachweislich', 'bewiesenermaßen']],
  ['soll', 'Der Täter ___ das Land bereits verlassen haben.', 'soll', ['hat', 'ist']],
  ['berufen', 'Die Zeitung beruft sich ___ anonyme Quellen.', 'auf', ['an', 'über']],
]

function rwDrills(): Exercise[] {
  return RW.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `rw-${id}`,
      type: 'multiple_choice' as const,
      topic: 'quellenangabe',
      concept: 'choose-marker',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'laut + noun (before), … zufolge (after, dative), wie … berichtet (clause), sollen = it is said, angeblich = allegedly, sich berufen auf.',
        'laut + isim (önce), … zufolge (sonra, Dativ), wie … berichtet (yan cümle), sollen = söyleniyor, angeblich = güya, sich berufen auf.',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

