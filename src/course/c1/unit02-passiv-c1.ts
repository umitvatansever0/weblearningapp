const PAS: [string, string, string, [string, string]][] = [
  ['zustand', 'Das Geschäft ___ seit acht Uhr geöffnet.', 'ist', ['hat', 'wurde']],
  ['worden', 'Der Täter ist gestern verhaftet ___.', 'worden', ['geworden', 'wurden']],
  ['musste', 'Das Dach ___ nach dem Sturm dringend repariert werden.', 'musste', ['wurde', 'hat']],
  ['haette', 'Das Problem ___ viel früher gelöst werden müssen.', 'hätte', ['wäre', 'ist']],
  ['es', '___ wird hier nicht geraucht.', 'Es', ['Man', 'Wir']],
  ['durch', 'Das Haus wurde ___ einen Brand zerstört.', 'durch', ['von', 'mit']],
]

function pasDrills(): Exercise[] {
  return PAS.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `pas-${id}`,
      type: 'multiple_choice' as const,
      topic: 'passivformen',
      concept: 'choose-form',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'State: sein + participle. Perfect: ist … worden (not geworden). Modal past: musste … werden; criticism: hätte … werden müssen. Impersonal: Es wird … Cause: durch + accusative.',
        'Durum: sein + ortaç. Perfekt: ist … worden (geworden değil). Modal geçmiş: musste … werden; eleştiri: hätte … werden müssen. Öznesiz: Es wird … Sebep: durch + Akk.',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

