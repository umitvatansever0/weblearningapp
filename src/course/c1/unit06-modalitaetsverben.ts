/** [id, sentence with gap, right, wrong] */
const MV: [string, string, string, [string, string]][] = [
  ['scheint', 'Er ___ heute sehr müde zu sein.', 'scheint', ['muss', 'soll']],
  ['droht', 'Das alte Haus ___ einzustürzen.', 'droht', ['will', 'kann']],
  ['brauchst', 'Du ___ nicht zu kommen, wenn du krank bist.', 'brauchst', ['musst', 'darfst']],
  ['haben', 'Alle Besucher ___ sich an die Hausordnung zu halten.', 'haben', ['müssen', 'sollen']],
  ['pflegt', 'Mein Großvater ___ nach dem Essen spazieren zu gehen.', 'pflegt', ['mag', 'will']],
  ['verspricht', 'Das Wochenende ___ sonnig zu werden.', 'verspricht', ['wird', 'soll']],
]

function mvDrills(): Exercise[] {
  return MV.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `mv-${id}`,
      type: 'multiple_choice' as const,
      topic: 'bedeutung',
      concept: 'choose-verb',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'These verbs take „zu“ + infinitive – real modal verbs (müssen, wollen, sollen …) never do. scheinen = seem, drohen = threaten, nicht brauchen = not need, haben zu = must, pflegen = usually do, versprechen = look like.',
        'Bu fiiller „zu“ + mastar alır – gerçek modal fiiller (müssen, wollen, sollen …) asla almaz. scheinen = görünmek, drohen = tehdit etmek, nicht brauchen = gerek yok, haben zu = zorunda olmak, pflegen = alışkanlık, versprechen = … olacağa benzemek.',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

