const ET: [string, string, string, [string, string]][] = [
  ['vertretbar', 'Ist es ethisch ___, Tiere für Kosmetik zu testen?', 'vertretbar', ['vertreten', 'vertretend']],
  ['abwaegen', 'Bei jeder neuen Technologie muss man Nutzen und Risiken sorgfältig ___.', 'abwägen', ['abwiegen', 'wägen ab']],
  ['ueberwiegen', 'Meiner Ansicht nach ___ die Vorteile der Gentechnik in der Medizin.', 'überwiegen', ['überwiegt', 'überwogen hat']],
  ['stellt', 'Es ___ sich die Frage, ob Maschinen über Leben entscheiden dürfen.', 'stellt', ['legt', 'setzt']],
  ['tragen', 'Wer soll die Verantwortung ___, wenn ein selbstfahrendes Auto einen Unfall verursacht?', 'tragen', ['machen', 'nehmen']],
  ['sicht', 'Aus ethischer ___ ist die totale Überwachung nicht zu rechtfertigen.', 'Sicht', ['Blick', 'Ansicht']],
]

function etDrills(): Exercise[] {
  return ET.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `et-${id}`,
      type: 'multiple_choice' as const,
      topic: 'werte',
      concept: 'ethics-phrases',
      skill: 'vocabulary' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Fixed phrases for ethical debates: ethisch vertretbar sein, Nutzen und Risiken abwägen, die Vorteile überwiegen, es stellt sich die Frage, ob …, die Verantwortung tragen, aus ethischer Sicht.',
        'Etik tartışmaları için kalıplar: ethisch vertretbar sein, Nutzen und Risiken abwägen, die Vorteile überwiegen, es stellt sich die Frage, ob …, die Verantwortung tragen, aus ethischer Sicht.',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

