/** [id, sentence with gap, right, wrong] */
const ZF: [string, string, string, [string, string]][] = [
  ['sei', 'Die Autorin schreibt, die Situation ___ besorgniserregend.', 'sei', ['ist gewesen', 'wäre gewesen']],
  ['behandelt', 'Der vorliegende Artikel ___ das Thema Fachkräftemangel.', 'behandelt', ['behandelte', 'hat behandeln']],
  ['zunaechst', '___ beschreibt der Autor die aktuelle Lage, anschließend nennt er Ursachen.', 'Zunächst', ['Schließlich', 'Abschließend']],
  ['hinweisen', 'Der Verfasser weist ___ hin, dass es kaum belastbare Daten gibt.', 'darauf', ['dafür', 'daran']],
  ['zufolge', 'Dem Autor ___ hat sich die Zahl der Pendler verdoppelt.', 'zufolge', ['laut', 'nach']],
  ['vertritt', 'Die Journalistin ___ die These, dass soziale Medien die Demokratie gefährden.', 'vertritt', ['vertreten', 'tritt']],
]

function zfDrills(): Exercise[] {
  return ZF.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `zf-${id}`,
      type: 'multiple_choice' as const,
      topic: 'neutral',
      concept: 'summary-language',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Summary language: present tense (behandelt), Konjunktiv I for the author’s statements (sei, habe), structure words (zunächst, anschließend, abschließend), darauf hinweisen, dass …, dem Autor zufolge, eine These vertreten.',
        'Özet dili: şimdiki zaman (behandelt), yazarın ifadeleri için Konjunktiv I (sei, habe), yapı kelimeleri (zunächst, anschließend, abschließend), darauf hinweisen, dass …, dem Autor zufolge, eine These vertreten.',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

