/** [id, sentence with gap, right, wrong] */
const RJ: [string, string, string, [string, string]][] = [
  ['anspruch', 'Jeder Arbeitnehmer hat Anspruch ___ mindestens 20 Tage bezahlten Urlaub.', 'auf', ['an', 'für']],
  ['gemaess', '___ Arbeitsvertrag beträgt die Kündigungsfrist drei Monate.', 'Gemäß', ['Gemäß des', 'Laut des']],
  ['sofern', '___ der Mieter die Miete nicht zahlt, darf der Vermieter kündigen.', 'Sofern', ['Sodass', 'Sowie']],
  ['verpflichtet', 'Der Arbeitgeber ist ___, den Lohn pünktlich zu zahlen.', 'verpflichtet', ['verpflichtend', 'verpflichtung']],
  ['berufung', 'Der Angeklagte will gegen das Urteil Berufung ___.', 'einlegen', ['machen', 'geben']],
  ['freigesprochen', 'Aus Mangel an Beweisen wurde die Angeklagte ___.', 'freigesprochen', ['freigesagt', 'losgesprochen']],
]

function rjDrills(): Exercise[] {
  return RJ.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `rj-${id}`,
      type: 'multiple_choice' as const,
      topic: 'rechtssprache',
      concept: 'legal-forms',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Legal German: Anspruch auf + accusative, gemäß + dative (often without article: gemäß Vertrag), sofern = provided that (verb at the end), verpflichtet sein, … zu …, Berufung einlegen, freisprechen (participle: freigesprochen).',
        'Hukuk Almancası: Anspruch auf + Akkusativ, gemäß + Dativ (çoğu zaman tanımlıksız: gemäß Vertrag), sofern = … koşuluyla (fiil sonda), verpflichtet sein, … zu …, Berufung einlegen, freisprechen (ortaç: freigesprochen).',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

