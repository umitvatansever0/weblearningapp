/** [id, sentence with gap, right, wrong] */
const K2: [string, string, string, [string, string]][] = [
  ['haette', '___ ich das gewusst, wäre ich früher gekommen.', 'Hätte', ['Wenn', 'Wäre']],
  ['waere', '___ der Zug pünktlich gewesen, hätten wir den Anschluss erreicht.', 'Wäre', ['Hätte', 'Wenn']],
  ['worden', 'Wenn das Problem früher erkannt ___ wäre, hätte man viel Geld gespart.', 'worden', ['geworden', 'würde']],
  ['sonst', 'Ich musste rennen, ___ hätte ich den letzten Bus verpasst.', 'sonst', ['deshalb', 'obwohl']],
  ['beinahe', 'Ich ___ beinahe meinen Pass zu Hause vergessen.', 'hätte', ['wäre', 'würde']],
  ['wuerde', 'Ich ___ vorschlagen, dass wir das Thema vertagen.', 'würde', ['wurde', 'wäre']],
]

function k2Drills(): Exercise[] {
  return K2.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `k2-${id}`,
      type: 'multiple_choice' as const,
      topic: 'formen',
      concept: 'choose-form',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Without wenn the verb (hätte / wäre) goes to position 1. Passive past: wäre … worden. sonst + Konjunktiv II = otherwise this would have happened. beinahe + hätte/wäre = almost (it didn’t happen).',
        'wenn olmadan fiil (hätte / wäre) 1. konuma gider. Geçmiş edilgen: wäre … worden. sonst + Konjunktiv II = yoksa bu olurdu. beinahe + hätte/wäre = neredeyse (olmadı).',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

