function psDrills(): Exercise[] {
  return PS.map(([id, clause, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `ps-${id}`,
      type: 'multiple_choice' as const,
      topic: 'umformen',
      concept: 'paraphrase',
      skill: 'reading' as const,
      difficulty: 3 as const,
      prompt: `„${clause}“ – Was bedeutet das?`,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Partizip II clauses usually mean „after / because“, Partizip I clauses „while“. Fixed phrases (zugegeben, abgesehen von) have their own meaning.',
        'Partizip II yan cümleleri genelde „… -den sonra / … için“, Partizip I yan cümleleri „… -iken“ anlamına gelir. Kalıplar (zugegeben, abgesehen von) kendi anlamlarına sahiptir.',
        `→ ${right}`
      ),
    }
  })
}

