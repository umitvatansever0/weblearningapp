const SI: [string, string, string, [string, string]][] = [
  ['studierenden', 'Alle ___ müssen sich bis Freitag für die Prüfung anmelden.', 'Studierenden', ['Studierende', 'Studierender']],
  ['lehrkraefte', 'Die ___ der Schule haben einen neuen Stundenplan erstellt.', 'Lehrkräfte', ['Lehrkraft', 'Lehrkräften']],
  ['doppel', 'Liebe Kolleginnen ___ Kollegen, ich begrüße Sie herzlich.', 'und', ['oder', 'sowie die']],
  ['praegt', 'Die Sprache, mit der wir aufwachsen, ___ unser Denken.', 'prägt', ['prägen', 'geprägt']],
  ['verdraengt', 'Manche befürchten, dass das Englische das Deutsche zunehmend ___.', 'verdrängt', ['verdrängen', 'verdrängte sich']],
  ['dialekt', 'Wer ___ spricht, wird manchmal zu Unrecht für weniger gebildet gehalten.', 'Dialekt', ['Dialekts', 'Dialekten']],
]

function siDrills(): Exercise[] {
  return SI.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `si-${id}`,
      type: 'multiple_choice' as const,
      topic: 'gendern',
      concept: 'forms',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Participles as nouns decline like adjectives: alle Studierenden (after alle → -en), die Lehrkräfte (neutral plural). Doppelnennung: Kolleginnen und Kollegen. Verbs agree with their subject: die Sprache prägt, das Englische verdrängt.',
        'İsim olarak kullanılan ortaçlar sıfat gibi çekimlenir: alle Studierenden (alle’den sonra → -en), die Lehrkräfte (nötr çoğul). Çift anma: Kolleginnen und Kollegen. Fiil özneye uyar: die Sprache prägt, das Englische verdrängt.',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

