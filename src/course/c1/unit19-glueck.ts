/** [id, sentence with gap, right, wrong] */
const GL: [string, string, string, [string, string]][] = [
  ['insofern', 'Geld macht nur ___ glücklich, als es existenzielle Sorgen beseitigt.', 'insofern', ['insoweit dass', 'sofern']],
  ['jenachdem', '___, wen man fragt, bedeutet Glück etwas völlig anderes.', 'Je nachdem', ['Je desto', 'Nachdem']],
  ['streben', 'Seit der Antike streben Menschen ___ einem erfüllten Leben.', 'nach', ['zu', 'auf']],
  ['abhaengen', 'Ob jemand glücklich ist, hängt weniger vom Einkommen ___ als von Beziehungen.', 'ab', ['an', 'aus']],
  ['vielmehr', 'Glück ist kein Zustand, ___ ein Weg.', 'sondern vielmehr', ['aber vielmehr', 'sondern trotzdem']],
  ['grunde', 'Im ___ geht es allen Philosophen um dieselbe Frage.', 'Grunde', ['Grund', 'Gründen']],
]

function glDrills(): Exercise[] {
  return GL.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `gl-${id}`,
      type: 'multiple_choice' as const,
      topic: 'abstrakt',
      concept: 'abstract-connectors',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Abstract argumentation: insofern … als (insofar as), je nachdem, ob / wer / wie (depending on), streben nach + dative, abhängen von (… hängt von … ab), nicht …, sondern vielmehr (not …, but rather), im Grunde (basically – fixed dative -e).',
        'Soyut tartışma: insofern … als (… olduğu ölçüde), je nachdem, ob / wer / wie (… -e bağlı olarak), streben nach + Dativ, abhängen von (… hängt von … ab), nicht …, sondern vielmehr (… değil, aksine), im Grunde (esasen – kalıplaşmış Dativ -e).',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

