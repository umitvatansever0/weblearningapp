/** [id, sentence with gap, right, wrong] */
const GS: [string, string, string, [string, string]][] = [
  ['richten', 'Die Beiträge zur Krankenversicherung richten sich ___ dem Einkommen.', 'nach', ['von', 'an']],
  ['beruht', 'Das System beruht ___ dem Solidarprinzip.', 'auf', ['an', 'über']],
  ['herrscht', 'In vielen Kliniken ___ ein akuter Mangel an Pflegekräften.', 'herrscht', ['regiert', 'befindet']],
  ['uebernimmt', 'Die Krankenkasse ___ die Kosten für die Operation.', 'übernimmt', ['nimmt über', 'überholt']],
  ['wuerde', 'Eine bessere Bezahlung ___ den Beruf attraktiver machen.', 'würde', ['wurde', 'wird gewesen']],
  ['damit', 'Die Löhne müssen steigen, ___ mehr junge Menschen den Pflegeberuf wählen.', 'damit', ['um', 'deshalb']],
]

function gsDrills(): Exercise[] {
  return GS.map(([id, sentence, right, wrong], i) => {
    const options = [right, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `gs-${id}`,
      type: 'multiple_choice' as const,
      topic: 'reformen',
      concept: 'collocations',
      skill: 'grammar' as const,
      difficulty: 3 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        'Key structures: sich richten nach (to depend on), beruhen auf (to be based on), es herrscht ein Mangel (there is a shortage), die Kosten übernehmen (inseparable). Proposals: würde + infinitive; purpose with different subjects: damit.',
        'Önemli yapılar: sich richten nach (… -e göre belirlenmek), beruhen auf (… -e dayanmak), es herrscht ein Mangel (bir eksiklik var), die Kosten übernehmen (ayrılmaz). Öneriler: würde + mastar; farklı öznelerle amaç: damit.',
        `→ ${right}`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

