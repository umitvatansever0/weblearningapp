/** [id, direct question, indirect intro, indirect clause (verb at the end)] */
const INDIRECT: [string, string, string, string][] = [
  ['bahnhof', 'Wo ist der Bahnhof?', 'Wissen Sie,', 'wo der Bahnhof ist?'],
  ['bus', 'Wann kommt der Bus?', 'Können Sie mir sagen,', 'wann der Bus kommt?'],
  ['kosten', 'Wie viel kostet das Ticket?', 'Darf ich fragen,', 'wie viel das Ticket kostet?'],
  ['offen', 'Ist das Museum heute offen?', 'Wissen Sie,', 'ob das Museum heute offen ist?'],
  ['kommt', 'Kommt Lisa morgen?', 'Weißt du,', 'ob Lisa morgen kommt?'],
  ['heisst', 'Wie heißt der neue Kollege?', 'Weißt du,', 'wie der neue Kollege heißt?'],
]

function indirectDrills(): Exercise[] {
  return INDIRECT.map(([id, direct, intro, clause], i) => {
    const right = `${intro} ${clause}`
    // wrong A: keep the direct word order after the intro
    const directLower = direct[0].toLowerCase() + direct.slice(1)
    const isYesNo = clause.startsWith('ob ')
    const wrongA = isYesNo ? `${intro} ${directLower}` : `${intro} ${directLower}`
    // wrong B: wrong conjunction
    const wrongB = isYesNo ? `${intro} ${clause.replace(/^ob /, 'wenn ')}` : `${intro} ${clause.replace(/^(\p{L}+(?: viel)?) /u, 'ob ')}`
    const options = [right, wrongA, wrongB]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `indirekt-${id}`,
      type: 'multiple_choice' as const,
      topic: isYesNo ? 'ob' : 'w-indirekt',
      concept: isYesNo ? 'ob-clause' : 'w-indirect',
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: direct,
      promptL10n: l('Ask the same question indirectly.', 'Aynı soruyu dolaylı sor.', 'Stell die Frage indirekt.'),
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: isYesNo
        ? l('Yes/no question → ob + verb at the end.', 'Evet/hayır sorusu → ob + fiil sonda.', 'ob + Verb am Ende.')
        : l('W-question → the W-word stays, the verb goes to the end.', 'W-sorusu → soru kelimesi kalır, fiil sona gider.', 'W-Wort + Verb am Ende.'),
      examples: [right],
    }
  })
}

