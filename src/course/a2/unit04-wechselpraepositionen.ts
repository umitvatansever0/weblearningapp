type Gender = 'm' | 'f' | 'n'
const DAT: Record<Gender, string> = { m: 'dem', f: 'der', n: 'dem' }
const AKK: Record<Gender, string> = { m: 'den', f: 'die', n: 'das' }

/** [id, sentence with ___ before the noun, case, gender] */
const CASE_DRILLS: [string, string, 'Dativ' | 'Akkusativ', Gender][] = [
  ['tisch-wo', 'Das Handy liegt auf ___ Tisch.', 'Dativ', 'm'],
  ['tisch-wohin', 'Ich lege das Handy auf ___ Tisch.', 'Akkusativ', 'm'],
  ['wand-wo', 'Das Foto hängt an ___ Wand.', 'Dativ', 'f'],
  ['wand-wohin', 'Wir hängen das Foto an ___ Wand.', 'Akkusativ', 'f'],
  ['regal-wo', 'Die Bücher stehen in ___ Regal.', 'Dativ', 'n'],
  ['regal-wohin', 'Stell die Bücher in ___ Regal!', 'Akkusativ', 'n'],
  ['bett-wo', 'Der Koffer ist unter ___ Bett.', 'Dativ', 'n'],
  ['schrank-wohin', 'Er stellt den Stuhl neben ___ Schrank.', 'Akkusativ', 'm'],
  ['kueche-wo', 'Mama ist in ___ Küche.', 'Dativ', 'f'],
  ['sofa-wohin', 'Die Katze springt auf ___ Sofa.', 'Akkusativ', 'n'],
]

function caseDrills(): Exercise[] {
  return CASE_DRILLS.map(([id, sentence, kasus, gender], i) => {
    const right = kasus === 'Dativ' ? DAT[gender] : AKK[gender]
    const other = kasus === 'Dativ' ? AKK[gender] : DAT[gender]
    const third = ['dem', 'den', 'der', 'die', 'das'].find((a) => a !== right && a !== other) as string
    const options = [right, other, third]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    const question = kasus === 'Dativ' ? 'Wo?' : 'Wohin?'
    return {
      id: `wp-${id}`,
      type: 'multiple_choice' as const,
      topic: kasus === 'Dativ' ? 'wo-dativ' : 'wohin-akk',
      concept: kasus === 'Dativ' ? 'wo-dativ' : 'wohin-akk',
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        `${question} → ${kasus}. ${gender === 'm' ? 'der' : gender === 'f' ? 'die' : 'das'} → ${right}.`,
        `${question} → ${kasus}. ${gender === 'm' ? 'der' : gender === 'f' ? 'die' : 'das'} → ${right}.`,
        `${question} → ${kasus}: ${right}.`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

