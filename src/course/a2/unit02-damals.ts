type Person = 'ich' | 'du' | 'er' | 'wir' | 'ihr' | 'sie'
const ENDINGS: Record<Person, string> = { ich: '', du: 'st', er: '', wir: 'n', ihr: 't', sie: 'n' }

/** Präteritum of sein/haben/modal verbs: stem + ending (ich/er have no ending). */
export function preterite(stem: string, person: Person): string {
  if (stem === 'war') return { ich: 'war', du: 'warst', er: 'war', wir: 'waren', ihr: 'wart', sie: 'waren' }[person]
  return `${stem}${ENDINGS[person]}`
}

/** [id, sentence with ___, infinitive, stem, person] */
const FORM_DRILLS: [string, string, string, string, Person][] = [
  ['war-ich', 'Als Kind ___ ich sehr schüchtern.', 'sein', 'war', 'ich'],
  ['war-wir', 'Gestern ___ wir im Kino.', 'sein', 'war', 'wir'],
  ['war-du', 'Wo ___ du am Wochenende?', 'sein', 'war', 'du'],
  ['hatte-er', 'Mein Opa ___ einen Bauernhof.', 'haben', 'hatte', 'er'],
  ['hatte-wir', 'Wir ___ keinen Fernseher.', 'haben', 'hatte', 'wir'],
  ['konnte-ich', 'Mit sechs ___ ich schon lesen.', 'können', 'konnte', 'ich'],
  ['musste-du', '___ du früher auch so früh aufstehen?', 'müssen', 'musste', 'du'],
  ['wollte-sie', 'Meine Schwestern ___ immer Ärztinnen werden.', 'wollen', 'wollte', 'sie'],
  ['durfte-ihr', '___ ihr abends lange draußen spielen?', 'dürfen', 'durfte', 'ihr'],
]

const WRONG: Record<string, (p: Person) => string[]> = {
  war: (p) => (p === 'ich' || p === 'er' ? ['bin', 'warst'] : p === 'du' ? ['bist', 'war'] : p === 'wir' ? ['sind', 'wart'] : ['seid', 'waren']),
  hatte: (p) => (p === 'er' ? ['hat', 'hattet'] : ['haben', 'hattet']),
  konnte: () => ['kann', 'könnte'],
  musste: () => ['musst', 'müsstest'],
  wollte: () => ['wollen', 'wolltet'],
  durfte: () => ['dürft', 'durften'],
}

function formDrills(): Exercise[] {
  return FORM_DRILLS.map(([id, sentence, inf, stem, person], i) => {
    const right = preterite(stem, person)
    const capital = sentence.startsWith('___')
    const cap = (s: string) => (capital ? s[0].toUpperCase() + s.slice(1) : s)
    const wrong = WRONG[stem](person).filter((w) => w !== right)
    const options = [...new Set([cap(right), ...wrong.map(cap)])].slice(0, 3)
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `prt-${id}`,
      type: 'multiple_choice' as const,
      topic: inf === 'sein' || inf === 'haben' ? 'war-hatte' : 'modal-past',
      concept: `prt-${stem}`,
      skill: 'grammar' as const,
      difficulty: (inf === 'sein' || inf === 'haben' ? 1 : 2) as 1 | 2,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(cap(right)),
      explanation: l(
        `${inf} in the Präteritum: ${person} → ${right}.`,
        `${inf} Präteritum’da: ${person} → ${right}.`,
        `${inf} im Präteritum: ${person} ${right}.`
      ),
      examples: [sentence.replace('___', `**${cap(right)}**`)],
    }
  })
}

