/** [time digits, official spoken, everyday spoken] */
const TIMES: [string, string, string][] = [
  ['14:35', 'vierzehn Uhr fünfunddreißig', 'fünf nach halb drei'],
  ['9:15', 'neun Uhr fünfzehn', 'Viertel nach neun'],
  ['18:45', 'achtzehn Uhr fünfundvierzig', 'Viertel vor sieben'],
  ['20:30', 'zwanzig Uhr dreißig', 'halb neun'],
  ['7:50', 'sieben Uhr fünfzig', 'zehn vor acht'],
]

function timeDrills(): Exercise[] {
  return TIMES.map(([digits, official], i) => {
    const others = TIMES.filter(([d]) => d !== digits)
    const options = [digits, others[i % others.length][0], others[(i + 1) % others.length][0]]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `uhr-${digits.replace(':', '')}`,
      type: 'listening_choice' as const,
      topic: 'uhrzeit',
      concept: 'official-time',
      skill: 'listening' as const,
      difficulty: 2 as const,
      audio: `Der Zug fährt um ${official} ab.`,
      question: l('When does the train leave?', 'Tren ne zaman kalkıyor?', 'Wann fährt der Zug ab?'),
      options: ordered,
      answer: ordered.indexOf(digits),
      explanation: l(`„${official}“ = ${digits} (24-hour clock).`, `„${official}“ = ${digits} (24 saat sistemi).`, `${official} = ${digits}.`),
    }
  })
}

/** [id, sentence with ___, prefix answer, verb] */
const PREFIX_DRILLS: [string, string, string, string][] = [
  ['ab', 'Der ICE fährt pünktlich um 10:04 Uhr ___.', 'ab', 'abfahren'],
  ['an', 'Wann kommen wir in Berlin ___?', 'an', 'ankommen'],
  ['um', 'Wir steigen in Fulda ___.', 'um', 'umsteigen'],
  ['ein', 'Bitte steigen Sie jetzt ___!', 'ein', 'einsteigen'],
  ['aus', 'Ich steige an der nächsten Haltestelle ___.', 'aus', 'aussteigen'],
]

function prefixDrills(): Exercise[] {
  const all = ['ab', 'an', 'um', 'ein', 'aus']
  return PREFIX_DRILLS.map(([id, sentence, prefix, verb], i) => {
    const wrong = all.filter((p) => p !== prefix)
    const options = [prefix, wrong[i % wrong.length], wrong[(i + 2) % wrong.length]]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `sep-${id}`,
      type: 'multiple_choice' as const,
      topic: 'trennbar',
      concept: `sep-${verb}`,
      skill: 'grammar' as const,
      difficulty: 1 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(prefix),
      explanation: l(`${verb}: the prefix „${prefix}“ goes to the end.`, `${verb}: „${prefix}“ ön eki sona gider.`, `${verb}: „${prefix}“ am Ende.`),
      examples: [sentence.replace('___', `**${prefix}**`)],
    }
  })
}

