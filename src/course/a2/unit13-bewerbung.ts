/** [id, sentence with ___, right, distractors, explanation key] */
const TIME_DRILLS: [string, string, 'seit' | 'vor' | 'für', string][] = [
  ['seit-jahren', 'Ich wohne ___ drei Jahren in Leipzig.', 'seit', 'still true today'],
  ['vor-jahren', 'Ich bin ___ drei Jahren nach Leipzig gezogen.', 'vor', 'finished event in the past'],
  ['fuer-monate', 'Im Sommer gehe ich ___ zwei Monate nach Spanien.', 'für', 'planned period'],
  ['seit-2020', '___ 2020 arbeite ich bei einer Bank.', 'seit', 'started then, still true'],
  ['vor-woche', 'Ich habe ___ einer Woche meine Bewerbung geschickt.', 'vor', 'finished event in the past'],
  ['seit-montag', 'Ich bin ___ Montag krank.', 'seit', 'started Monday, still ill'],
]

const TIME_TR: Record<string, string> = {
  'still true today': 'bugün hâlâ geçerli',
  'finished event in the past': 'geçmişte bitmiş olay',
  'planned period': 'planlanan süre',
  'started then, still true': 'o zaman başladı, hâlâ geçerli',
  'started Monday, still ill': 'pazartesi başladı, hâlâ hasta',
}

function timeDrills(): Exercise[] {
  return TIME_DRILLS.map(([id, sentence, right, why], i) => {
    const options: string[] = ['seit', 'vor', 'für']
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)].map((o) => (sentence.startsWith('___') ? o[0].toUpperCase() + o.slice(1) : o))
    const shown = sentence.startsWith('___') ? right[0].toUpperCase() + right.slice(1) : right
    return {
      id: `zeit-${id}`,
      type: 'multiple_choice' as const,
      topic: 'seit-vor-fuer',
      concept: `time-${right}`,
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(shown),
      explanation: l(`${why} → ${right}.`, `${TIME_TR[why]} → ${right}.`, `→ ${right}.`),
      examples: [sentence.replace('___', `**${shown}**`)],
    }
  })
}

