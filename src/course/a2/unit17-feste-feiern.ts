/** Ordinal stem: 1–19 → -t, 20+ → -st (with the irregular 1st, 3rd, 7th, 8th). */
export function ordinalStem(n: number): string {
  const irregular: Record<number, string> = { 1: 'erst', 3: 'dritt', 7: 'siebt', 8: 'acht' }
  if (irregular[n]) return irregular[n]
  const words: Record<number, string> = {
    2: 'zwei', 4: 'vier', 5: 'fünf', 6: 'sechs', 9: 'neun', 10: 'zehn', 11: 'elf', 12: 'zwölf',
    13: 'dreizehn', 14: 'vierzehn', 15: 'fünfzehn', 16: 'sechzehn', 17: 'siebzehn', 18: 'achtzehn', 19: 'neunzehn',
    20: 'zwanzig', 21: 'einundzwanzig', 24: 'vierundzwanzig', 30: 'dreißig', 31: 'einunddreißig',
  }
  return n < 20 ? `${words[n]}t` : `${words[n]}st`
}

/** [day, month] – „am …en <Monat>“ */
const DATES: [number, string][] = [
  [1, 'Januar'],
  [3, 'Oktober'],
  [7, 'Juli'],
  [12, 'März'],
  [20, 'Juni'],
  [24, 'Dezember'],
  [31, 'Dezember'],
]

function dateDrills(): Exercise[] {
  return DATES.map(([day, month], i) => {
    const right = `${ordinalStem(day)}en`
    const wrongA = day < 20 ? `${ordinalStem(day).replace(/t$/, '')}sten` : `${ordinalStem(day).replace(/st$/, '')}ten`
    const wrongB = day === 1 ? 'einsten' : day === 3 ? 'dreiten' : day === 7 ? 'siebenten' : `${ordinalStem(day)}e`
    const options = [...new Set([right, wrongA, wrongB])]
    const rotation = i % options.length
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `datum-${day}-${month.toLowerCase().replace('ä', 'ae')}`,
      type: 'multiple_choice' as const,
      topic: 'datum',
      concept: day === 1 || day === 3 || day === 7 ? 'ordinal-irregular' : day < 20 ? 'ordinal-t' : 'ordinal-st',
      skill: 'grammar' as const,
      difficulty: 2 as const,
      prompt: `${day}. ${month} → am ___ ${month}`,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        day === 1 || day === 3 || day === 7
          ? `Irregular: ${day}. → ${ordinalStem(day)}-. After „am“: -en → am ${right} ${month}.`
          : day < 20
            ? `1–19: number + -t-. After „am“: -en → am ${right} ${month}.`
            : `From 20: number + -st-. After „am“: -en → am ${right} ${month}.`,
        day === 1 || day === 3 || day === 7
          ? `Düzensiz: ${day}. → ${ordinalStem(day)}-. „am“dan sonra: -en → am ${right} ${month}.`
          : day < 20
            ? `1–19: sayı + -t-. „am“dan sonra: -en → am ${right} ${month}.`
            : `20’den itibaren: sayı + -st-. „am“dan sonra: -en → am ${right} ${month}.`,
        `am ${right} ${month}.`
      ),
      examples: [`am **${right}** ${month}`],
    }
  })
}

