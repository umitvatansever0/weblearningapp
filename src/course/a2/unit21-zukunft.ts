const WERDEN: Record<string, string> = { ich: 'werde', du: 'wirst', er: 'wird', wir: 'werden', ihr: 'werdet', Sie: 'werden' }

/** [id, sentence with ___ for werden, person] */
const WERDEN_DRILLS: [string, string, keyof typeof WERDEN][] = [
  ['ich', 'Ich ___ nächstes Jahr mehr Sport machen.', 'ich'],
  ['du', '___ du morgen zur Party kommen?', 'du'],
  ['er', 'Mein Bruder ___ im Sommer heiraten.', 'er'],
  ['wir', 'Wir ___ bald in eine größere Wohnung ziehen.', 'wir'],
  ['ihr', '___ ihr in den Ferien verreisen?', 'ihr'],
  ['es', 'Es ___ morgen wahrscheinlich regnen.', 'er'],
]

const WERDEN_WRONG: Record<string, [string, string]> = {
  ich: ['wird', 'wirst'],
  du: ['Werdest', 'Wird'],
  er: ['werdet', 'wirst'],
  wir: ['werdet', 'wird'],
  ihr: ['Werden', 'Wirst'],
}

function werdenDrills(): Exercise[] {
  return WERDEN_DRILLS.map(([id, sentence, person], i) => {
    const cap = sentence.startsWith('___')
    const right = cap ? WERDEN[person][0].toUpperCase() + WERDEN[person].slice(1) : WERDEN[person]
    const options = [right, ...WERDEN_WRONG[person]]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    return {
      id: `futur-${id}`,
      type: 'multiple_choice' as const,
      topic: 'futur',
      concept: `werden-${person}`,
      skill: 'grammar' as const,
      difficulty: 1 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(right),
      explanation: l(
        `Futur I: werden (${person === 'er' ? 'er/sie/es' : person} → ${WERDEN[person]}) + infinitive at the end.`,
        `Futur I: werden (${person === 'er' ? 'er/sie/es' : person} → ${WERDEN[person]}) + mastar sonda.`,
        `${WERDEN[person]} + Infinitiv.`
      ),
      examples: [sentence.replace('___', `**${right}**`)],
    }
  })
}

