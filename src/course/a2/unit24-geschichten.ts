/** [infinitive, Präteritum (ich/er), two wrong forms] */
const PRAET: [string, string, [string, string]][] = [
  ['gehen', 'ging', ['gehte', 'gang']],
  ['kommen', 'kam', ['kommte', 'kom']],
  ['sehen', 'sah', ['sehte', 'sieh']],
  ['finden', 'fand', ['findete', 'fund']],
  ['fahren', 'fuhr', ['fahrte', 'fähr']],
  ['geben', 'gab', ['gebte', 'gib']],
  ['sagen', 'sagte', ['sag', 'sug']],
  ['machen', 'machte', ['mach', 'much']],
  ['spielen', 'spielte', ['spiel', 'spol']],
]

function praetDrills(): Exercise[] {
  return PRAET.map(([inf, form, wrong], i) => {
    const options = [form, ...wrong]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    const regular = form.endsWith('te')
    return {
      id: `prt-${inf}`,
      type: 'multiple_choice' as const,
      topic: 'praeteritum',
      concept: regular ? 'prt-regular' : 'prt-irregular',
      skill: 'grammar' as const,
      difficulty: (regular ? 1 : 2) as 1 | 2,
      prompt: `${inf} → er ___`,
      options: ordered,
      answer: ordered.indexOf(form),
      explanation: regular
        ? l(`Regular: stem + -te: ${form}.`, `Düzenli: kök + -te: ${form}.`, `regelmäßig: ${form}.`)
        : l(`Irregular – learn it as a word: ${inf} → ${form}.`, `Düzensiz – kelime olarak öğren: ${inf} → ${form}.`, `unregelmäßig: ${form}.`),
      examples: [`Er **${form}** …`],
    }
  })
}

