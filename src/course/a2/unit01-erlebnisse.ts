/** [infinitive, participle, auxiliary, sentence with ___ for the auxiliary (ich/wir/er form)] */
const AUX_DRILLS: [string, string, 'bin' | 'habe' | 'ist' | 'hat' | 'sind' | 'haben', string][] = [
  ['fahren', 'gefahren', 'bin', 'Ich ___ mit dem Zug nach Wien gefahren.'],
  ['gehen', 'gegangen', 'ist', 'Lisa ___ früh ins Bett gegangen.'],
  ['fliegen', 'geflogen', 'sind', 'Wir ___ nach Antalya geflogen.'],
  ['bleiben', 'geblieben', 'bin', 'Am Sonntag ___ ich zu Hause geblieben.'],
  ['aufstehen', 'aufgestanden', 'ist', 'Mein Vater ___ um fünf Uhr aufgestanden.'],
  ['essen', 'gegessen', 'habe', 'Im Urlaub ___ ich viel Fisch gegessen.'],
  ['besuchen', 'besucht', 'haben', 'Letzte Woche ___ wir unsere Tante besucht.'],
  ['schwimmen', 'geschwommen', 'sind', 'Am Nachmittag ___ wir im Meer geschwommen.'],
  ['kaufen', 'gekauft', 'hat', 'Tom ___ einen neuen Koffer gekauft.'],
  ['kommen', 'gekommen', 'ist', 'Der Bus ___ zu spät gekommen.'],
]

const SAME_PERSON: Record<string, [string, string]> = {
  bin: ['habe', 'ist'],
  habe: ['bin', 'hat'],
  ist: ['hat', 'sind'],
  hat: ['ist', 'habe'],
  sind: ['haben', 'seid'],
  haben: ['sind', 'hat'],
}

function auxDrills(): Exercise[] {
  return AUX_DRILLS.map(([inf, part, aux, sentence], i) => {
    const options = [aux, ...SAME_PERSON[aux]]
    const rotation = i % 3
    const ordered = [...options.slice(rotation), ...options.slice(0, rotation)]
    const usesSein = ['bin', 'ist', 'sind'].includes(aux)
    return {
      id: `aux-${inf}`,
      type: 'multiple_choice' as const,
      topic: 'sein-haben',
      concept: usesSein ? 'aux-sein' : 'aux-haben',
      skill: 'grammar' as const,
      difficulty: 1 as const,
      prompt: sentence,
      options: ordered,
      answer: ordered.indexOf(aux),
      explanation: usesSein
        ? l(
            `${inf} is a verb of movement or change → sein: ${aux} … ${part}.`,
            `${inf} hareket ya da değişim bildirir → sein: ${aux} … ${part}.`,
            `${inf}: Bewegung/Veränderung → sein.`
          )
        : l(
            `${inf} has an object / no movement from A to B → haben: ${aux} … ${part}.`,
            `${inf} nesne alır / A’dan B’ye hareket yok → haben: ${aux} … ${part}.`,
            `${inf} → haben.`
          ),
      examples: [sentence.replace('___', `**${aux}**`)],
    }
  })
}

